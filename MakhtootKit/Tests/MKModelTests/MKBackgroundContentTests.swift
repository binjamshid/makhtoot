import Foundation
import Testing
@testable import MKModel

/// P5.3 back-compat fix (coordinator review finding, TWICE-CORRECTED):
/// `MKBackgroundContent.image` gained a `fit: MKBackgroundImageFit`
/// associated value. The first attempt left `Codable` synthesized, which
/// silently changed the on-disk JSON shape and broke decoding of any
/// `scene.json` written before `fit` existed. The SECOND attempt (custom
/// `init(from:)`/`encode(to:)`) assumed a single-unlabeled-associated-value
/// enum case encodes its payload BARE ، also wrong, caught by running
/// `MKPersistenceTests` against a real on-disk fixture
/// (`Tests/Fixtures/fixture-5000-nodes.makhtoot`, predating this session):
/// its `.solid` background payload is actually `{"_0": {…}}`, not the bare
/// object. Swift's synthesized enum `Codable` always wraps EVERY
/// associated value (even a lone unlabeled one) under a keyed container
/// (`_0` for unlabeled, the parameter label otherwise) ، confirmed by an
/// isolated probe: `enum E { case a(Int) }; JSONEncoder().encode(E.a(5))`
/// → `{"a":{"_0":5}}`.
///
/// The literals below are transcribed from that REAL fixture's actual
/// on-disk bytes (`.solid`) and from applying the same, now-confirmed
/// wrapping rule to the pre-P5.3 `.image(MKAssetRef)` shape (`.image`),
/// NOT generated by encoding the current type and stripping a key ، a
/// strip-based test would only prove this type's own encoder and decoder
/// agree with each other, not that a REAL pre-P5.3 `scene.json` still
/// decodes. `MKBackgroundContent`'s custom `init(from:)`/`encode(to:)`
/// (`MKNode.swift`, "P5.3 back-compat fix ، CORRECTED" section) is what
/// this suite guards.
@Suite("MKBackgroundContent Codable (P5.3 back-compat)")
struct MKBackgroundContentTests {
    @Test func legacyImagePayloadWithNoFitKeyDecodesToCover() throws {
        // The real pre-P5.3 shape: `.image(MKAssetRef)`, one unlabeled
        // associated value, synthesized-Codable-wrapped under "_0" (per
        // this suite's header, confirmed against real on-disk data and an
        // isolated probe) ، no "fit" key exists at all.
        let legacyJSON = #"{"image":{"_0":{"digest":"deadbeef","ext":"jpg"}}}"#
        let decoded = try JSONDecoder().decode(MKBackgroundContent.self, from: Data(legacyJSON.utf8))

        guard case .image(let ref, let fit) = decoded else {
            Issue.record("expected .image, got \(decoded)")
            return
        }
        #expect(ref == MKAssetRef(digest: "deadbeef", ext: "jpg"))
        #expect(fit == .cover)
    }

    @Test func realFixtureSolidBackgroundBytesStillDecode() throws {
        // Transcribed VERBATIM from `Tests/Fixtures/fixture-5000-nodes
        // .makhtoot/scene.json`'s `background.content` object (a real,
        // on-disk, pre-this-session document) ، this is the literal that
        // caught the second attempt's bug: it decodes one level deeper
        // (`"_0"`) than that attempt assumed.
        let realFixtureJSON = #"{"solid":{"_0":{"a":1,"b":1,"g":1,"r":1,"space":"srgb"}}}"#
        let decoded = try JSONDecoder().decode(MKBackgroundContent.self, from: Data(realFixtureJSON.utf8))
        #expect(decoded == .solid(MKSolidColor(r: 1, g: 1, b: 1, a: 1)))
    }

    @Test func explicitlySetContainSurvivesAnEncodeDecodeRoundTrip() throws {
        let content = MKBackgroundContent.image(MKAssetRef(digest: "cafebabe", ext: "png"), fit: .contain)

        let data = try JSONEncoder().encode(content)
        let decoded = try JSONDecoder().decode(MKBackgroundContent.self, from: data)
        #expect(decoded == content)

        // Also asserts the ON-DISK shape stays the historical `_0`-wrapped
        // nesting (`fit` a SIBLING of `_0`, not folded into it) ، made
        // structurally explicit rather than only checked via round-trip
        // equality, so a future accidental reshuffle fails loudly here.
        let object = try #require(try JSONSerialization.jsonObject(with: data) as? [String: Any])
        let imagePayload = try #require(object["image"] as? [String: Any])
        let refPayload = try #require(imagePayload["_0"] as? [String: Any])
        #expect(refPayload["digest"] as? String == "cafebabe")
        #expect(refPayload["ext"] as? String == "png")
        #expect(imagePayload["fit"] as? String == "contain")
    }

    @Test func coverRoundTripsAndOmittingFitOnDecodeDefaultsToCover() throws {
        let content = MKBackgroundContent.image(MKAssetRef(digest: "abc123", ext: "heic"), fit: .cover)
        let data = try JSONEncoder().encode(content)
        let decoded = try JSONDecoder().decode(MKBackgroundContent.self, from: data)
        #expect(decoded == content)
    }

    @Test func solidRoundTripsThroughJSONUnchanged() throws {
        let content = MKBackgroundContent.solid(MKSolidColor(r: 0.2, g: 0.4, b: 0.6, a: 0.8))
        let data = try JSONEncoder().encode(content)
        let decoded = try JSONDecoder().decode(MKBackgroundContent.self, from: data)
        #expect(decoded == content)
    }
}

import Foundation

// WS-14 packet §5 task 2 (the legal core). `MKAssetProvenance` mirrors the
// WS-09 font-license-capture discipline (FOUNDATION §12: "no invented
// legal/policy facts") for non-font bundled assets. Every shipped asset
// (checked by `AssetProvenanceAudit`, T12) carries exactly one of these.

/// Where an asset's vector geometry came from. `originalWork` is the v1
/// default and, per this run's posture (packet §6: "all v1 assets are
/// original vector works... nothing is redistributed"), the ONLY case any
/// bundled asset in this library actually uses. `derivedVerified` exists as
/// a modeled, testable case for a future asset built from a verified,
/// license-captured external source ، packet task 2's sourcing rules
/// explicitly restrict it ("derivation permitted ONLY from sources with
/// verified redistribution licenses... avoid entirely in v1").
public enum MKAssetOrigin: Hashable, Sendable, Codable, Equatable {
    /// Authored directly for Makhtoot ، procedurally constructed geometry
    /// (e.g. girih/star-polygon constructions from mathematical
    /// definitions) or hand-authored control points. `author` records the
    /// attribution or the method used to construct the geometry.
    /// `date` uses ISO 8601 so the record stays stable across JSON encoders.
    case originalWork(author: String, date: String)

    /// Derived from a verified, redistribution-licensed external source.
    /// `licenseFilePath` MUST point at a captured license file under this
    /// module's resources (never a URL alone ، "captured license file" per
    /// task 2's rule 4); `sourceLicense` is the license's short name/id
    /// (e.g. "CC0-1.0"); `transformationNote` records what was changed from
    /// the source (task 2 rule 2/3 ، traceable derivation, not a blind
    /// copy).
    case derivedVerified(sourceURL: String, sourceLicense: String, licenseFilePath: String, transformationNote: String)
}

/// One asset's provenance record (task 2). `assetID` links back to
/// `MKAssetDescriptor.assetID`/`provenanceRef` ، kept as an explicit field
/// (rather than relying on dictionary-key positioning alone) so a single
/// exported record is independently meaningful and so
/// `AssetProvenanceAudit` can report a mismatch as a structural error, not
/// just a missing dictionary entry.
public struct MKAssetProvenance: Hashable, Sendable, Codable, Equatable {
    public var assetID: String
    public var origin: MKAssetOrigin
    /// The verification record or the person who checked the license file.
    public var verifiedBy: String
    /// Free-text construction/derivation notes ، e.g. "12-fold rosette from
    /// {12/5} star polygon, recorded in WS-14, 2026" (packet's own example,
    /// task 5). `AssetProvenanceAudit` greps these notes for forbidden
    /// sources (T7's "zero font-derived paths" check; task 2's forbidden
    /// list).
    public var notes: String

    public init(assetID: String, origin: MKAssetOrigin, verifiedBy: String, notes: String) {
        self.assetID = assetID
        self.origin = origin
        self.verifiedBy = verifiedBy
        self.notes = notes
    }
}

/// Substrings that must never appear in a provenance record's `notes` ،
/// `AssetProvenanceAudit` (T12) fails any record whose notes mention one of
/// these (task 2 rule 3's forbidden-source list, made mechanically
/// checkable). Matching is case-insensitive substring search; the list is
/// deliberately conservative (a false positive just means renaming a note,
/// a false negative is the real risk).
public enum MKAssetForbiddenSourceMarkers {
    public static let markers: [String] = [
        "clip-art", "clipart", "free vector", "freepik", "vecteezy", "flaticon",
        "shutterstock", "istock", "getty", "traced from", "ai-traced", "ai generated",
        "generated by ai", "stable diffusion", "midjourney", "dall-e", "font glyph",
        "derived from font", "glyph outline", "uthmani", "kfgqpc",
    ]

    /// Whether `notes` contains any forbidden-source marker (case-insensitive).
    public static func containsForbiddenMarker(_ notes: String) -> Bool {
        let lowered = notes.lowercased()
        return markers.contains { lowered.contains($0) }
    }
}
